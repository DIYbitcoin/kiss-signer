#!/usr/bin/env python3
"""Write docs/practice/index.html from what sim/mk_practice_page.sh built.

Reads, from the build folder:
  facts.jsonl        the device's own verdict and amounts for each transaction
  <name>.qr          one QR symbol per line: size, a space, the modules as 0/1
  seed.qr            the practice seed's SeedQR
Every QR is inlined as its module bits and drawn on a canvas by a few lines of
script, so the page is one file with no library and no network request.
Standard library only.
"""
import html
import json
import sys
from pathlib import Path

SEED = ("abandon abandon abandon abandon abandon abandon "
        "abandon abandon abandon abandon abandon about")

# (fixture, heading, what to do, the verdict the page promises)
TXS = [
    ("01-native", "1. A normal payment",
     "Slide to sign. KISS then shows the signed transaction as a QR. There is "
     "nothing to scan it into, and that is fine: it was never real.",
     "READY"),
    ("05-caution-highfee", "2. A payment with a warning",
     "KISS warns that the fee is high. Read the warning and accept it before "
     "the slide will move. This is how KISS asks you to look twice.",
     "CAUTION"),
    ("04-stop-wrongnet", "3. A payment KISS refuses",
     "This one is for real bitcoin, not testnet, so KISS stops and signs "
     "nothing. A refusal always says why.",
     "STOP"),
]


def sats(n):
    return f"{n:,}".replace(",", " ") + " sats"


def symbols(path):
    out = []
    for line in path.read_text().splitlines():
        size, bits = line.split(" ")
        assert len(bits) == int(size) ** 2, path
        out.append({"n": int(size), "b": bits})
    assert out, path
    return out


def main(build, dest):
    build = Path(build)
    facts = {}
    for line in (build / "facts.jsonl").read_text().splitlines():
        f = json.loads(line)
        facts[Path(f["file"]).stem] = f
    data = {"seed": symbols(build / "seed.qr")[0]}
    cards = []
    for stem, title, todo, want in TXS:
        f = facts[stem]
        # The page promises a verdict; the device has to agree, and a
        # transaction it accepts has to sign.
        assert f["status"] == want, (stem, f["status"], want)
        assert f["signs"] == (want != "STOP"), (stem, f)
        data[stem] = symbols(build / f"{stem}.qr")
        if want == "STOP":
            shows = f'KISS says <b class="bad">{html.escape(f["reason"])}</b>.'
        else:
            shows = (f'KISS shows <b>{sats(f["send"])}</b> going out and a fee of '
                     f'<b>{sats(f["fee"])}</b>.')
        cards.append(f"""
      <div class="card">
        <h2>{html.escape(title)}</h2>
        <canvas class="qr" data-q="{stem}" width="330" height="330"></canvas>
        <p class="mut ctr" data-c="{stem}"></p>
        <p>{shows}</p>
        <p>{html.escape(todo)}</p>
      </div>""")

    words = "".join(f"<li>{w}</li>" for w in SEED.split())
    page = PAGE.replace("@@WORDS@@", words) \
               .replace("@@CARDS@@", "".join(cards)) \
               .replace("@@DATA@@", json.dumps(data, separators=(",", ":")))
    Path(dest).write_text(page)


